/**
 * 获取某级某类的指标列表
 */
export function getIndicators(level, category) {
  return STANDARD_INDICATORS.filter(
    (i) => i.level === level && i.category === category,
  )
}

/**
 * 按级别分组
 */
export function groupByLevel() {
  const baseline = STANDARD_INDICATORS.filter((i) => i.level === 'baseline')
  const enhanced = STANDARD_INDICATORS.filter((i) => i.level === 'enhanced')
  return { baseline, enhanced }
}

/**
 * 按 级别 → 类别 分组
 */
export function groupByLevelAndCategory() {
  const result = {}
  for (const lv of STANDARD_LEVELS) {
    result[lv.key] = {}
    for (const cat of CATEGORIES) {
      result[lv.key][cat.key] = STANDARD_INDICATORS.filter(
        (i) => i.level === lv.key && i.category === cat.key,
      )
    }
  }
  return result
}
