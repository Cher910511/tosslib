/**
 * 生成指标的自动评分记录（供评分弹窗预填）。
 * @param {object} ind 指标配置
 * @param {object} item 软件条目（含 vulnCount/lang/license/repoUrl 等扫描数据）
 * @returns {{ score: number, params: object } | null}
 */
export function autoScoreRecord(ind, item) {
  if (!ind || !ind.capable) return null
  const scorer = AUTO_SCORERS[ind.id]
  if (!scorer) return null
  const r = scorer(item || {}, ind)
  if (!r || typeof r.score !== 'number' || Number.isNaN(r.score)) return null
  return { score: Math.min(10, Math.max(0, r.score)), params: r.params || {} }
}
